"""Generate the TypeScript and Python constant modules from the registry.

    python3 scripts/generate.py           write both generated modules
    python3 scripts/generate.py --check   exit 1 if a generated module is stale

The registry (registry/gen-ai.json) is the single source: a curated subset of
the OpenTelemetry GenAI semantic conventions pinned to one upstream version,
plus the blueprint's own `agenticai.*` extensions and the legacy names that
are normalized to canonical ones.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
REGISTRY = ROOT / "registry" / "gen-ai.json"
TS_OUT = ROOT / "src" / "generated" / "registry.ts"
PY_OUT = ROOT / "python" / "agenticai_semconv" / "_generated.py"

HEADER = "Generated by scripts/generate.py from registry/gen-ai.json. Do not edit."


def constant_name(key: str) -> str:
    return key.upper().replace(".", "_")


def load() -> dict:
    registry = json.loads(REGISTRY.read_text(encoding="utf-8"))
    attributes = registry["attributes"]
    extensions = registry["extensions"]
    for old, new in registry["legacyAttributes"].items():
        if old in attributes:
            raise SystemExit(f"{old} is both canonical and legacy")
        if new is not None and new not in attributes:
            raise SystemExit(f"legacy {old} maps to unknown attribute {new}")
    for old, new in registry["legacyExtensions"].items():
        if new not in attributes and new not in extensions:
            raise SystemExit(f"legacy extension {old} maps to unknown attribute {new}")
    for key, values in registry["legacyValues"].items():
        if key not in attributes:
            raise SystemExit(f"legacyValues names unknown attribute {key}")
        allowed = {
            "gen_ai.operation.name": registry["operations"],
            "gen_ai.provider.name": registry["providers"],
        }.get(key)
        for new in values.values():
            if allowed is not None and new not in allowed:
                raise SystemExit(f"legacy value for {key} maps to unknown value {new}")
    return registry


def renames(registry: dict) -> dict[str, str]:
    out = {k: v for k, v in registry["legacyAttributes"].items() if v is not None}
    out.update(registry["legacyExtensions"])
    return dict(sorted(out.items()))


def removed(registry: dict) -> list[str]:
    return sorted(k for k, v in registry["legacyAttributes"].items() if v is None)


def required(registry: dict) -> list[str]:
    merged = {**registry["attributes"], **registry["extensions"]}
    return sorted(k for k, v in merged.items() if v["tier"] == "required")


def list_typed(registry: dict) -> list[str]:
    merged = {**registry["attributes"], **registry["extensions"]}
    return sorted(k for k, v in merged.items() if v["type"].endswith("[]"))


def render_ts(registry: dict) -> str:
    merged = {**registry["attributes"], **registry["extensions"]}
    lines = [
        "/*",
        " * Copyright Amazon.com, Inc. or its affiliates. All Rights Reserved.",
        " * SPDX-License-Identifier: MIT-0",
        " *",
        f" * {HEADER}",
        " */",
        "",
        f"export const SEMCONV_UPSTREAM_VERSION = {json.dumps(registry['upstream']['version'])};",
        "",
    ]
    for key in sorted(merged):
        lines.append(f"export const {constant_name(key)} = {json.dumps(key)};")
    lines += [
        "",
        "export const ATTRIBUTE_TYPES: Readonly<Record<string, string>> = {",
        *[f"  {json.dumps(k)}: {json.dumps(merged[k]['type'])}," for k in sorted(merged)],
        "};",
        "",
        f"export const REQUIRED_ATTRIBUTES: readonly string[] = {json.dumps(required(registry))};",
        f"export const LIST_ATTRIBUTES: readonly string[] = {json.dumps(list_typed(registry))};",
        "",
        f"export const GEN_AI_OPERATIONS = {json.dumps(registry['operations'])} as const;",
        "export type GenAiOperationName = (typeof GEN_AI_OPERATIONS)[number];",
        "",
        f"export const GEN_AI_PROVIDERS = {json.dumps(registry['providers'])} as const;",
        "export type GenAiProviderName = (typeof GEN_AI_PROVIDERS)[number];",
        "",
        "/** Legacy attribute name to canonical name. */",
        f"export const LEGACY_ATTRIBUTE_RENAMES: Readonly<Record<string, string>> = {json.dumps(renames(registry), indent=2)};",
        "",
        "/** Attributes removed upstream with no replacement; dropped on normalization. */",
        f"export const REMOVED_ATTRIBUTES: readonly string[] = {json.dumps(removed(registry))};",
        "",
        "/** Per-attribute legacy value to canonical value. */",
        f"export const LEGACY_VALUE_RENAMES: Readonly<Record<string, Readonly<Record<string, string>>>> = {json.dumps(registry['legacyValues'], indent=2, sort_keys=True)};",
        "",
    ]
    return "\n".join(lines)


def render_py(registry: dict) -> str:
    merged = {**registry["attributes"], **registry["extensions"]}
    lines = [
        "# Copyright Amazon.com, Inc. or its affiliates. All Rights Reserved.",
        "# SPDX-License-Identifier: MIT-0",
        "#",
        f"# {HEADER}",
        '"""Constants for the pinned GenAI semantic conventions subset."""',
        "",
        f"SEMCONV_UPSTREAM_VERSION = {json.dumps(registry['upstream']['version'])}",
        "",
    ]
    for key in sorted(merged):
        lines.append(f"{constant_name(key)} = {json.dumps(key)}")
    lines += [
        "",
        "ATTRIBUTE_TYPES = {",
        *[f"    {json.dumps(k)}: {json.dumps(merged[k]['type'])}," for k in sorted(merged)],
        "}",
        "",
        f"REQUIRED_ATTRIBUTES = tuple({json.dumps(required(registry))})",
        f"LIST_ATTRIBUTES = frozenset({json.dumps(list_typed(registry))})",
        "",
        f"GEN_AI_OPERATIONS = tuple({json.dumps(registry['operations'])})",
        f"GEN_AI_PROVIDERS = tuple({json.dumps(registry['providers'])})",
        "",
        "LEGACY_ATTRIBUTE_RENAMES = {",
        *[f"    {json.dumps(k)}: {json.dumps(v)}," for k, v in renames(registry).items()],
        "}",
        "",
        f"REMOVED_ATTRIBUTES = frozenset({json.dumps(removed(registry))})",
        "",
        "LEGACY_VALUE_RENAMES = {",
        *[
            f"    {json.dumps(k)}: {json.dumps(v, sort_keys=True)},"
            for k, v in sorted(registry["legacyValues"].items())
        ],
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if generated modules are stale")
    args = parser.parse_args()
    registry = load()
    outputs = {TS_OUT: render_ts(registry), PY_OUT: render_py(registry)}
    stale = [path for path, text in outputs.items() if not path.exists() or path.read_text(encoding="utf-8") != text]
    if args.check:
        for path in stale:
            print(f"stale: {path.relative_to(ROOT)} (run python3 scripts/generate.py)", file=sys.stderr)
        return 1 if stale else 0
    for path, text in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
